import { createRequire } from "node:module";
const { chromium } = createRequire(import.meta.url)("playwright-core");
import { spawn } from "node:child_process";
import path from "node:path";
import { startTcp, startUsbRelay } from "./fake-device.mjs";
const HERE = path.dirname(new URL(import.meta.url).pathname);
const ok = (n, c, x = "") => { console.log(c ? "  ✓" : "  ✗", n, x); if (!c) process.exitCode = 1; };
await startTcp(15555); startUsbRelay(15556);
const srv = spawn("sh", [path.join(HERE, "../dist/pwa/start-annex.sh")], { env: { ...process.env, DISPLAY: "" }, stdio: "ignore" });
await new Promise((r) => setTimeout(r, 1500));
const browser = await chromium.launch({ executablePath: process.env.CHROME_PATH || undefined, args: ["--no-proxy-server"] });
const ctx = await browser.newContext();
await ctx.addInitScript({ path: path.join(HERE, "usb-mock.js") });
const page = await ctx.newPage();
const errs = []; page.on("pageerror", (e) => errs.push(String(e)));
page.on("console", (m) => m.type() === "error" && errs.push(m.text()));
await page.goto("http://localhost:27180/");
await page.waitForFunction(() => navigator.serviceWorker.ready.then(() => true), null, { timeout: 10000 });
await page.reload();
ok("service worker controls the page", await page.evaluate(() => !!navigator.serviceWorker.controller));
const cdp = await ctx.newCDPSession(page);
const inst = await cdp.send("Page.getInstallabilityErrors");
ok("installable (no installability errors)", inst.installabilityErrors.length === 0, JSON.stringify(inst.installabilityErrors));
const man = await cdp.send("Page.getAppManifest");
ok("manifest parsed", !man.errors?.length && /Annex/.test(man.data), JSON.stringify(man.errors));
ok("PWA hint hidden when served", !(await page.isVisible("#pwaHint")));
await page.click("#btnUsb");
ok("USB connect + stream work on the http origin", !!(await page.waitForFunction(() => window.annex.session?.width > 0, null, { timeout: 15000 }).catch(() => null)));
srv.kill(); await new Promise((r) => setTimeout(r, 500));
await page.evaluate(() => window.annex.disconnect());
await page.reload();
await page.waitForSelector("#btnUsb", { timeout: 8000 }).catch(() => {});
ok("loads offline with the server stopped", await page.isVisible("#btnUsb") || await page.evaluate(() => !!window.annex));
ok("no page errors", errs.length === 0, errs.join(" | "));
await browser.close(); process.exit();
